export type AderenciaCnae = 'com_parcelamento' | 'sem_parcelamento' | 'fora' | 'risco';

/**
 * Classifica um CNAE contra as bases de Aderência D1.
 * Lida com a inconsistência da planilha (mistura de 6 e 7 dígitos).
 *
 * Ordem de verificação (importante):
 * 1. Risco primeiro (bloqueia tudo)
 * 2. COM PARCELAMENTO (prioridade alta)
 * 3. SEM PARCELAMENTO (prioridade média)
 * 4. Fora (não qualifica)
 */
export function classificarCnae(cnaeCodigo: string | undefined | null): AderenciaCnae {
  const limpo = (cnaeCodigo || '').replace(/\D/g, '');
  if (!limpo) return 'fora';

  const formas = new Set<string>([limpo]);
  if (limpo.length === 6) formas.add(limpo + '0');
  if (limpo.length === 7 && limpo.endsWith('0')) formas.add(limpo.slice(0, 6));

  for (const f of formas) if (CNAE_RISCO.has(f)) return 'risco';
  for (const f of formas) if (CNAE_COM_PARCELAMENTO.has(f)) return 'com_parcelamento';
  for (const f of formas) if (CNAE_SEM_PARCELAMENTO.has(f)) return 'sem_parcelamento';
  return 'fora';
}

